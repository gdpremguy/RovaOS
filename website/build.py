"""Package the RovaOS download website using a real ISO and its checked digest.

Default output: build/website. This builds files; it does not publish them online.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import html
import json
import os
from pathlib import Path
import re
import shutil
import tempfile
from urllib.parse import urlsplit

SOURCE = Path(__file__).resolve().parent
ROOT = SOURCE.parent


def sha256(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def package(image, output, download_url=None):
    image = Path(image).resolve(strict=True)
    output = Path(output).resolve()
    if not image.is_file():
        raise ValueError('ISO must be a regular file')
    if output == ROOT or output in (SOURCE, *SOURCE.parents) or SOURCE in output.parents:
        raise ValueError('Output must not overwrite the website sources or project root')
    if output == image.parent or output in image.parents:
        raise ValueError('Output must not contain the source ISO')
    if download_url:
        parsed = urlsplit(download_url)
        if (parsed.scheme != 'https' or not parsed.hostname or parsed.username
                or parsed.password or parsed.fragment):
            raise ValueError('An external download URL must use HTTPS, without credentials or a fragment')
    with image.open('rb') as stream:
        stream.seek(32768)
        pvd = stream.read(2048)
    if pvd[:7] != b'\x01CD001\x01' or pvd[40:72].strip() != b'ROVA_LINUX':
        raise ValueError('Expected the RovaOS Linux ISO, not an unrelated or legacy image')
    signature = (image.stat().st_size, image.stat().st_mtime_ns)
    digest = sha256(image)
    checksum_file = Path(str(image)+'.sha256')
    parts = checksum_file.read_text(encoding='utf-8').strip().split(maxsplit=1)
    if len(parts) != 2 or parts[0].lower() != digest or parts[1].lstrip('*') != image.name:
        raise ValueError('ISO checksum does not match its sidecar; rebuild or investigate before publishing')
    if output.exists() and any(output.iterdir()) and not (output/'.rova-website').is_file():
        raise ValueError('Refusing to overwrite a nonempty directory not marked as generated website output')
    template = (SOURCE/'index.html').read_text(encoding='utf-8')
    values = {
        'ISO_URL': download_url or 'downloads/rovaos.iso',
        'ISO_SIZE': f'{signature[0] / 1024**2:,.0f} MiB',
        'BUILD_DATE': datetime.fromtimestamp(image.stat().st_mtime, timezone.utc).strftime('%d %b %Y'),
        'ISO_SHA256': digest,
    }
    def replace(match):
        if match[1] not in values:
            raise ValueError('Unknown template token: '+match[1])
        return html.escape(values[match[1]], quote=True)
    page = re.sub(r'\{\{([A-Z_0-9]+)\}\}', replace, template)
    output.mkdir(parents=True, exist_ok=True)
    (output/'.rova-website').write_text('Generated by website/build.py\n', encoding='utf-8')
    downloads = output/'downloads'
    downloads.mkdir(exist_ok=True)
    if not download_url:
        # A temporary file avoids exposing a half-copied ISO to a running server.
        fd, temporary = tempfile.mkstemp(prefix='.rovaos-', suffix='.partial', dir=downloads)
        os.close(fd)
        temporary = Path(temporary)
        try:
            shutil.copyfile(image, temporary)
            if sha256(temporary) != digest:
                raise ValueError('ISO changed while copying; no download published')
            if (image.stat().st_size, image.stat().st_mtime_ns) != signature:
                raise ValueError('ISO changed while packaging; retry after the build completes')
            os.replace(temporary, downloads/'rovaos.iso')
        finally:
            temporary.unlink(missing_ok=True)
    elif (image.stat().st_size, image.stat().st_mtime_ns) != signature:
        raise ValueError('ISO changed while packaging; retry after the build completes')
    assets = output/'assets'
    assets.mkdir(exist_ok=True)
    shutil.copyfile(ROOT/'assets/wallpapers/rova-horizon.png', assets/'horizon.png')
    shutil.copyfile(ROOT/'assets/wallpapers/HORIZON-NOTICE.txt', assets/'HORIZON-NOTICE.txt')
    shutil.copyfile(SOURCE/'assets/mark.svg', assets/'mark.svg')
    for name in ('styles.css', 'script.js'):
        shutil.copyfile(SOURCE/name, output/name)
    (downloads/'rovaos.iso.sha256').write_text(f'{digest}  rovaos.iso\n', encoding='utf-8')
    manifest = {'product': 'RovaOS', 'edition': 'Horizon / Niri', 'channel': 'preview',
                'architecture': 'x86-64', 'iso_url': values['ISO_URL'],
                'iso_bytes': signature[0], 'iso_sha256': digest,
                'built_date_utc': values['BUILD_DATE']}
    (output/'release.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
    (output/'index.html').write_text(page, encoding='utf-8')
    print(f'Website ready: {output}')
    print('Not published online. See website/README.md for hosting instructions.')
    return manifest


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--iso', type=Path, default=ROOT/'rovaos.iso')
    parser.add_argument('--output', type=Path, default=ROOT/'build/website')
    parser.add_argument('--download-url', help='HTTPS release/object-storage URL; omits the large local ISO copy')
    args = parser.parse_args()
    try:
        package(args.iso, args.output, args.download_url)
    except (OSError, ValueError) as error:
        parser.exit(1, f'Website not packaged: {error}\n')
